import pytest

from mod_weaver.core.effects import letter, to_st
from mod_weaver.errors import CellConflictError


@pytest.mark.parametrize("mod, st", [
    ((0x0, 0x00), (0, 0)),
    ((0x0, 0x37), (letter("J"), 0x37)),
    ((0x1, 0x05), (letter("F"), 0x05)),
    ((0x2, 0xF0), (letter("E"), 0xDF)),          # 0xE0 以上は fine slide と解釈されるので丸める
    ((0x3, 0x18), (letter("G"), 0x18)),
    ((0x4, 0x46), (letter("H"), 0x46)),
    ((0x9, 0x20), (letter("O"), 0x20)),
    ((0xA, 0x30), (letter("D"), 0x30)),
    ((0xA, 0x05), (letter("D"), 0x05)),
    ((0xB, 0x02), (letter("B"), 0x02)),
    ((0xD, 0x00), (letter("C"), 0x00)),
    ((0xE, 0x93), (letter("Q"), 0x03)),
    ((0xE, 0xD2), (letter("S"), 0xD2)),
    ((0xE, 0xC4), (letter("S"), 0xC4)),
    ((0xE, 0x12), (letter("F"), 0xF2)),
    ((0xF, 0x06), (letter("A"), 0x06)),
    ((0xF, 0x20), (letter("T"), 0x20)),
    ((0xF, 0x96), (letter("T"), 0x96)),
])
def test_translation_table(mod, st):
    assert to_st(*mod) == st


@pytest.mark.parametrize("mod", [(0x8, 0x40), (0x7, 0x11), (0xE, 0x50), (0xD, 0x10)])
def test_untranslatable_effects_raise(mod):
    with pytest.raises(CellConflictError):
        to_st(*mod)
